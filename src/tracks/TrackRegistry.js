const splineCache = new Map();

/**
 * Loads or generates the full spline data for a given track ID.
 * If originalSplineData is provided and track is classic_grand_prix, returns original.
 */
export function getTrackSplineData(trackId, originalSplineData = null) {
  if (trackId === 'classic_grand_prix' && originalSplineData) {
    return originalSplineData;
  }

  if (splineCache.has(trackId)) {
    return splineCache.get(trackId);
  }

  const def = TRACK_DEFINITIONS.find((t) => t.id === trackId) || TRACK_DEFINITIONS[0];

  if (def.isOriginal && originalSplineData) {
    splineCache.set(def.id, originalSplineData);
    return originalSplineData;
  }

  const generated = generateSplineDataFromControlPoints({
    id: def.id,
    name: def.name,
    description: def.description,
    sectors: def.sectors,
    controlPoints: def.controlPoints,
    track_width_m: 0.022,
    curb_width_m: 0.0025,
    rail_height_m: 0.0035,
    start_index: 0,
    atmosphereSettings: def.atmosphere,
  });

  splineCache.set(def.id, generated);
  return generated;
}

/**
 * Retrieves the stored best lap time for a track from localStorage.
 */
export function getTrackBestLap(trackId) {
  try {
    const raw = localStorage.getItem(`desk_racer_best_lap_${trackId}`);
    return raw ? parseFloat(raw) : null;
  } catch {
    return null;
  }
}

/**
 * Saves a new best lap time for a track to localStorage.
 */
export function setTrackBestLap(trackId, lapTime) {
  try {
    const curr = getTrackBestLap(trackId);
    if (curr === null || lapTime < curr) {
      localStorage.setItem(`desk_racer_best_lap_${trackId}`, String(lapTime));
      return true;
    }
  } catch {
    // Ignore storage restrictions
  }
  return false;
}
